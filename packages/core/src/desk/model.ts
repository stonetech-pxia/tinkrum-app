import { OFFICE_MIME_BY_EXT, mediaKindOf } from '../media';

// Desk in the file room (file-room DESIGN §3, §11.1, D-357): holds working copies on the desk,
// creating a new version with each tool usage, supporting undo and redo. Contains pure logic only
// (version stacks, limits, version merging, cleanup prompts); file copying and deletion are handled
// by the app according to paths computed here. All paths are relative paths within the desk
// directory (absolute document directory paths change on iOS after app updates). Records only tool
// IDs, excluding parameters, file contents, and recognized text; inaccessible to the AI (D-042,
// D-113).

/** Recent version limit (confirmed by founder 2026-10-30, §10 question 2). */
export const DESK_MAX_VERSIONS = 20;
/** Maximum total size across all versions (whichever limit is hit first). */
export const DESK_MAX_BYTES = 500 * 1024 * 1024;
/** Days of inactivity before prompting for cleanup (prompt only, no automatic deletion). */
export const DESK_STALE_DAYS = 7;

/** A file in the desk directory (relative path) along with its size. */
export interface DeskBlob {
  path: string;
  size: number;
}

/**
 * Intermediate format (§11.1): TableDoc for Excel conversion, DocDoc for Word conversion. JSON
 * serves as the "source" for this version, while the desk's xlsx/docx are generated products
 * derived from it. Assets are referenced images (such as pages used for source image screenshots
 * or extracted images embedded in docx), shared across versions.
 */
export interface DeskSource extends DeskBlob {
  kind: 'table' | 'doc';
  /** Pages where recognition scope was set to "table content only" but no ruled tables were found (Excel conversion, 1-indexed). */
  pagesWithoutTables?: number[];
  assets: DeskBlob[];
  /**
   * Whether intermediate format was parsed from external docx/xlsx (D-509): 'original' means the
   * desk file is a copy of the original (unmodified), 'rebuilt' means regenerated from the
   * intermediate format after modifications (some original formatting is lost; user is notified
   * before first save).
   */
  imported?: 'original' | 'rebuilt';
}

/** A file on the desk (as it appeared in a specific version). */
export interface DeskFile extends DeskBlob {
  /** ID of this file on the desk: new files generated by tools receive new IDs. */
  id: string;
  /** Display name without extension (local only). */
  name: string;
  ext: string;
  mimeType: string;
  width?: number;
  height?: number;
  pageCount?: number;
  durationMs?: number;
  source?: DeskSource;
}

/** Origin of this version: records only tool or quick action IDs, excluding parameters (which may contain user-written text). */
export type DeskStep =
  | { kind: 'place' }
  | { kind: 'action'; action: string }
  | { kind: 'workflow'; workflowId: string }
  /** An edit session on a table or document (R2): consecutive edits are merged into a single version. */
  | { kind: 'edit' };

export interface DeskVersion {
  /** Version number, starting from 1; not re-indexed when old versions are deleted. */
  n: number;
  by: DeskStep;
  at: number;
  files: DeskFile[];
  /** Unsealed edit (§11.2): subsequent edits directly replace this version without creating a new one. */
  open?: true;
}

export interface Desk {
  version: 1;
  id: string;
  createdAt: number;
  /** Timestamp of last modification (placed on desk, used tool, undo, redo). Used to calculate cleanup prompts. */
  touchedAt: number;
  versions: DeskVersion[];
  /** Index of currently displayed version; subsequent versions are retained after undo to allow redo. */
  current: number;
  nextN: number;
}

export interface DeskLimits {
  maxVersions: number;
  maxBytes: number;
}

export const DESK_LIMITS: DeskLimits = {
  maxVersions: DESK_MAX_VERSIONS,
  maxBytes: DESK_MAX_BYTES,
};

/** Result of an operation: the new desk, along with files that are no longer used by any version and can be deleted. */
export interface DeskChange {
  desk: Desk;
  drop: string[];
}

export function newDesk(id: string, files: DeskFile[], now: number): Desk {
  return {
    version: 1,
    id,
    createdAt: now,
    touchedAt: now,
    versions: [{ n: 1, by: { kind: 'place' }, at: now, files }],
    current: 0,
    nextN: 2,
  };
}

export const currentVersion = (desk: Desk): DeskVersion => desk.versions[desk.current]!;
export const currentFiles = (desk: Desk): DeskFile[] => currentVersion(desk).files;

/** All desk files used by a file: itself, intermediate formats, and images referenced by intermediate formats. */
export function blobsOf(file: DeskFile): DeskBlob[] {
  return [file, ...(file.source ? [file.source, ...file.source.assets] : [])].map(
    ({ path, size }) => ({ path, size }),
  );
}

function blobsOfVersions(versions: readonly DeskVersion[]): Map<string, number> {
  const out = new Map<string, number>();
  for (const v of versions)
    for (const f of v.files) for (const b of blobsOf(f)) out.set(b.path, b.size);
  return out;
}

/** Total size occupied by the desk: shared files (cross-version images, unchanged files) are counted only once. */
export const deskBytes = (desk: Desk): number =>
  [...blobsOfVersions(desk.versions).values()].reduce((a, b) => a + b, 0);

/** Paths present in `before` but absent in `after`. */
function dropped(before: readonly DeskVersion[], after: readonly DeskVersion[]): string[] {
  const keep = blobsOfVersions(after);
  return [...blobsOfVersions(before).keys()].filter((p) => !keep.has(p));
}

const sealed = (v: DeskVersion): DeskVersion => {
  if (!v.open) return v;
  const { open: _open, ...rest } = v;
  return rest;
};

/**
 * Generate a new version (via tool, quick action, or edit session). If undone, subsequent
 * versions are discarded (redo no longer possible). If `by` is 'edit' and current version is an
 * unsealed edit, replace it directly (merging consecutive edits, §10 question 4). When exceeding
 * limits, delete from the oldest while always keeping the current version.
 */
export function commitVersion(
  desk: Desk,
  files: DeskFile[],
  by: DeskStep,
  now: number,
  limits: DeskLimits = DESK_LIMITS,
): DeskChange {
  const head = currentVersion(desk);
  const kept = desk.versions.slice(0, desk.current + 1);
  let versions: DeskVersion[];
  let nextN = desk.nextN;
  if (by.kind === 'edit' && head.open) {
    versions = [...kept.slice(0, -1), { ...head, at: now, files }];
  } else {
    versions = [
      ...kept.slice(0, -1),
      sealed(head),
      { n: nextN++, by, at: now, files, ...(by.kind === 'edit' ? { open: true as const } : {}) },
    ];
  }
  while (
    versions.length > 1 &&
    (versions.length > limits.maxVersions || bytesOf(versions) > limits.maxBytes)
  ) {
    versions = versions.slice(1);
  }
  const next: Desk = { ...desk, versions, current: versions.length - 1, nextN, touchedAt: now };
  return { desk: next, drop: dropped(desk.versions, versions) };
}

const bytesOf = (versions: readonly DeskVersion[]) =>
  [...blobsOfVersions(versions).values()].reduce((a, b) => a + b, 0);

/** Seal unsealed edits (triggered when using other tools, saving, leaving the room, switching files, or app backgrounding, §11.2). */
export function sealEdit(desk: Desk): Desk {
  const head = currentVersion(desk);
  if (!head.open) return desk;
  return {
    ...desk,
    versions: desk.versions.map((v, i) => (i === desk.current ? sealed(v) : v)),
  };
}

export const canUndo = (desk: Desk) => desk.current > 0;
export const canRedo = (desk: Desk) => desk.current < desk.versions.length - 1;

/** Revert to the index-th version (undo, redo, revert to any step). Subsequent versions are retained so you can forward again. */
export function moveTo(desk: Desk, index: number, now: number): Desk {
  if (index < 0 || index >= desk.versions.length || index === desk.current) return desk;
  return { ...sealEdit(desk), current: index, touchedAt: now };
}

export const undoDesk = (desk: Desk, now: number) => moveTo(desk, desk.current - 1, now);
export const redoDesk = (desk: Desk, now: number) => moveTo(desk, desk.current + 1, now);

/**
 * How tool outputs are returned to the desk (§3.1):
 * - No file outputs (text recognition, read QR code): returns null, desk remains unchanged,
 * results are shown in the panel;
 * - One-to-many (splitting PDF, PDF to images): the original is retained, and the new files are
 * placed right after it;
 * - One-to-one, many-to-one (type may or may not change): replaces the files used, positioned at
 * the location of the first file. `selected` is the files passed to the tool for this run (desk
 * IDs); other files on the desk remain untouched.
 */
export function placeOutputs(
  files: readonly DeskFile[],
  selected: readonly string[],
  outputs: readonly DeskFile[],
): DeskFile[] | null {
  if (outputs.length === 0) return null;
  const used = files.filter((f) => selected.includes(f.id));
  if (used.length === 0) return [...files, ...outputs];
  if (outputs.length > used.length) {
    const last = files.indexOf(used.at(-1)!);
    return [...files.slice(0, last + 1), ...outputs, ...files.slice(last + 1)];
  }
  const first = files.indexOf(used[0]!);
  const rest = files.filter((f) => !selected.includes(f.id));
  const at = files.slice(0, first).filter((f) => !selected.includes(f.id)).length;
  return [...rest.slice(0, at), ...outputs, ...rest.slice(at)];
}

/** A desk that has not been touched for a long time and should trigger a cleanup prompt (prompt only, no automatic deletion). */
export function isStaleDesk(desk: Pick<Desk, 'touchedAt'>, now: number): boolean {
  return now - desk.touchedAt >= DESK_STALE_DAYS * 24 * 60 * 60 * 1000;
}

/**
 * The type of a file on a desk: determines how it is previewed and which tools are placed by
 * default in the toolbar. `sheet` is Excel; `doc` is other office documents (Word, RTF,
 * PowerPoint): all tools only convert to PDF, and docx with DocDoc uses the document view for
 * preview.
 */
export type DeskKind = 'image' | 'pdf' | 'sheet' | 'doc' | 'video' | 'audio' | 'other';

export const DESK_KINDS: readonly DeskKind[] = [
  'image',
  'pdf',
  'sheet',
  'doc',
  'video',
  'audio',
  'other',
];

export function deskKindOf(file: Pick<DeskFile, 'mimeType' | 'ext'>): DeskKind {
  const kind = mediaKindOf(file.mimeType, file.ext);
  if (kind === 'image' || kind === 'pdf' || kind === 'video' || kind === 'audio') return kind;
  // When the name has no file extension (common when shared from other Android apps), identify it by MIME type.
  const mime = file.mimeType.toLowerCase();
  const ext =
    file.ext.toLowerCase() in OFFICE_MIME_BY_EXT
      ? file.ext.toLowerCase()
      : (Object.keys(OFFICE_MIME_BY_EXT).find((e) => OFFICE_MIME_BY_EXT[e] === mime) ??
        (mime === 'application/rtf' ? 'rtf' : ''));
  if (ext === 'xlsx' || ext === 'xls') return 'sheet';
  if (ext) return 'doc';
  return 'other';
}

/** Read back the desk JSON; returns null if the format is invalid (treated as if the desk does not exist). */
export function parseDesk(json: string): Desk | null {
  try {
    const desk = JSON.parse(json) as Desk;
    if (desk?.version !== 1 || typeof desk.id !== 'string') return null;
    if (!Array.isArray(desk.versions) || desk.versions.length === 0) return null;
    if (!desk.versions.every((v) => Array.isArray(v?.files))) return null;
    if (!(desk.current >= 0 && desk.current < desk.versions.length)) return null;
    return desk;
  } catch {
    return null;
  }
}
