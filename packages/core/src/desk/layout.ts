import { z } from 'zod';

import { ComponentSchema, type Component } from '../components';
import { IdSchema, boundedText } from '../schema-primitives';

// Room layout (file-room DESIGN §4, §5, D-358): Confirmed by the founder in a session on
// 2026-10-30; preview centered and toolbar at the bottom by default, but this is a configuration
// that AI modifications can change (prompt rule 52, evaluation PD*, D-406). The only customizable
// aspects are: toolbar placement (top or bottom), preview size, thumbnail strip visibility, number
// of explanatory components above/below the preview, and available tools on each file type's
// toolbar. Unchangeable aspects (absent from the structure entirely): the preview itself (cannot be
// removed), files on the desk (D-113: AI does not touch file content), and table/document editing
// tools (which appear alongside selected items, §11.3), as well as executing anything on behalf of
// the user (all toolbar buttons require manual user taps).

/** Blocks allowed above and below the preview: limited to explanations and entry points, excluding data-mutating components (record forms). */
export const DESK_SLOT_TYPES = ['header', 'text', 'notice', 'spacer', 'button'] as const;

/** A block that may sit above or below the preview: no notice about entries, no button that runs a quick action or picks files. */
const fitsDeskSlot = (c: {
  look: string;
  source?: unknown;
  tools?: readonly unknown[] | undefined;
}) =>
  (DESK_SLOT_TYPES as readonly string[]).includes(c.look) &&
  !(c.look === 'notice' && c.source !== undefined) &&
  !(
    c.look === 'button' && c.tools?.some((u) => typeof u === 'object' && u !== null && 'tool' in u)
  );

/** Same as ActionIdSchema (schema.ts); schema.ts references this file, so it cannot import schema.ts back. */
const DeskActionIdSchema = z.string().regex(/^[a-z]+\.[a-zA-Z0-9]+$/, 'invalid action id');

/**
 * An item on the toolbar (v34 ToolRef): a single action from the catalog (optionally with a
 * common spec), or a quick action ID (invoked on desk files, formerly `{workflowId}`).
 */
export const DeskToolSchema = z.union([
  z.strictObject({ action: DeskActionIdSchema, preset: IdSchema.optional() }),
  IdSchema,
]);
export type DeskTool = z.infer<typeof DeskToolSchema>;

export const DeskToolGroupSchema = z.strictObject({
  /** Group name (text in configuration); omitted when no group name is displayed. */
  title: boundedText(1, 24).optional(),
  items: z.array(DeskToolSchema).min(1).max(20),
});
export type DeskToolGroup = z.infer<typeof DeskToolGroupSchema>;

const groups = z.array(DeskToolGroupSchema).min(1).max(6).optional();

const slot = z
  .array(ComponentSchema)
  .max(2)
  .refine((list) => list.every(fitsDeskSlot), {
    message: `only ${DESK_SLOT_TYPES.join(', ')} can go above or below the preview (no notice with source, no button that runs a quick action or picks files)`,
  })
  .optional();

/**
 * Room layout (containers.desk, since schemaVersion 33; moved into containers in v34, Q7). Every
 * property is optional and defaults to DEFAULT_DESK_LAYOUT when omitted. Tools are specified per
 * file type: unlisted types use default toolbars generated by the registry (defaultDeskTools).
 */
export const DeskLayoutSchema = z.strictObject({
  /** Toolbar placement below the preview (default) or above. */
  toolbar: z.enum(['bottom', 'top']).optional(),
  /** Preview size: fill occupies remaining space (default), large is about two-thirds of the screen, medium is about half. */
  preview: z.enum(['fill', 'large', 'medium']).optional(),
  /** File strip below the preview when multiple files are on the desk (shown by default). */
  strip: z.boolean().optional(),
  above: slot,
  below: slot,
  tools: z
    .strictObject({
      image: groups,
      pdf: groups,
      sheet: groups,
      doc: groups,
      video: groups,
      audio: groups,
      other: groups,
    })
    .optional(),
});
export type DeskLayout = z.infer<typeof DeskLayoutSchema>;
/** Configured toolbars for each file type (unlisted types use defaults). */
export type DeskToolsConfig = NonNullable<DeskLayout['tools']>;

export interface ResolvedDeskLayout {
  toolbar: 'bottom' | 'top';
  preview: 'fill' | 'large' | 'medium';
  strip: boolean;
  above: Component[];
  below: Component[];
  /** Types explicitly specified in configuration; unlisted types use default toolbars. */
  tools: DeskToolsConfig;
}

export const DEFAULT_DESK_LAYOUT: ResolvedDeskLayout = {
  toolbar: 'bottom',
  preview: 'fill',
  strip: true,
  above: [],
  below: [],
  tools: {},
};

/** Fills in default values for layout configurations (which may be undefined). */
export function resolveDeskLayout(layout: DeskLayout | undefined): ResolvedDeskLayout {
  return {
    toolbar: layout?.toolbar ?? DEFAULT_DESK_LAYOUT.toolbar,
    preview: layout?.preview ?? DEFAULT_DESK_LAYOUT.preview,
    strip: layout?.strip ?? DEFAULT_DESK_LAYOUT.strip,
    above: (layout?.above ?? []).filter((c) => !c.hidden),
    below: (layout?.below ?? []).filter((c) => !c.hidden),
    tools: layout?.tools ?? {},
  };
}
