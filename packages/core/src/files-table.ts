import type { Collection } from './schema-base';

// System table $files (v34 D-368, D-369 Q2): User files (saved to Morph, saved by quick actions,
// attachments, picked in file slots) treated as a read-only structured table. Fields are automatic;
// AI can only reference them in source and filter, cannot add fields or delete records, and cannot
// see file names or contents (Rule 3, D-042). Inbox batch, desktop working copies, and intermediate
// run results are workspace files and not here.

export const FILES_TABLE = '$files';

/** File kinds (one-to-one mapping with MIME major types: image/*, application/pdf, video/*, audio/*, sheet, doc, other). */
export const FILE_KINDS = ['image', 'pdf', 'video', 'audio', 'sheet', 'doc', 'other'] as const;
export type FileKind = (typeof FILE_KINDS)[number];

/** File origin: user picked (file slot, attachment, saved to Morph), or generated by a quick action. */
export const FILE_SOURCES = ['picked', 'generated'] as const;

/** Identify file kind from MIME type. */
export function fileKindOf(mimeType: string): FileKind {
  if (mimeType.startsWith('image/')) return 'image';
  if (mimeType === 'application/pdf') return 'pdf';
  if (mimeType.startsWith('video/')) return 'video';
  if (mimeType.startsWith('audio/')) return 'audio';
  if (
    mimeType === 'text/csv' ||
    mimeType.includes('spreadsheet') ||
    mimeType === 'application/vnd.ms-excel'
  )
    return 'sheet';
  if (mimeType.includes('wordprocessing') || mimeType === 'application/msword') return 'doc';
  return 'other';
}

/** Structure of $files (for filter checking and sorting; createdAt is a system field). Name is for AI viewing, not user content. */
export const FILES_COLLECTION: Collection = {
  id: 'files',
  name: 'Files',
  fields: [
    { id: 'name', name: 'Name', type: 'text' },
    {
      id: 'kind',
      name: 'Kind',
      type: 'choice',
      options: FILE_KINDS.map((id) => ({ id, label: id })),
    },
    { id: 'size', name: 'Size', type: 'number' },
    {
      id: 'source',
      name: 'Source',
      type: 'choice',
      options: FILE_SOURCES.map((id) => ({ id, label: id })),
    },
  ],
};
