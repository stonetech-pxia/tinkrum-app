import { z } from 'zod';

import type { DeskKind } from '../desk/model';
import { OpListSchema, type Op } from '../ops';
import type { Registry } from '../registry';
import type { Locale, WorkspaceConfig } from '../schema';

// AIProvider (§5.4, §14.2): takes a user utterance and current config, outputs a structured plan.
// mock and real model implement the same interface; plans always pass through PlanSchema and
// validateWorkspace before use.

/**
 * userData: request involves user record contents (read, write, delete, queries). AI only
 * modifies the UI, never touches records. errand: asking AI to run errands for the user instead
 * of modifying the app (writing emails, answering questions, summarizing file contents..., D-113,
 * D-128); explain in description what quick action can be created for it. unavailable: AI failed
 * to respond (connection lost, error, quota limit), generated by the app itself, never used by
 * the model (D-189: such refusals cannot be sent back as requirements).
 */
export type RejectReason =
  | 'unknown'
  | 'protected'
  | 'deleteFiles'
  | 'userData'
  | 'notInstalled'
  | 'noChange'
  | 'errand'
  | 'unavailable';

export const REJECT_REASONS = [
  'unknown',
  'protected',
  'deleteFiles',
  'userData',
  'notInstalled',
  'noChange',
  'errand',
  'unavailable',
] as const satisfies readonly RejectReason[];

export type Plan =
  | {
      kind: 'ops';
      ops: Op[];
      /**
       * Whether newly created quick action should have an entry point on home screen (D-109):
       * false = user said not to place; omitted = user checks in preview, checked by default.
       * When user wants it on home screen, AI directly adds look "action" block without using
       * this field.
       */
      homeEntry?: boolean;
      /**
       * Phrases in the preview under "Things you should know" (interface language, D-110): parts
       * that cannot be done (e.g., no scheduled runs, monthly manual tapping required), and why
       * steps added by the AI for a purpose are needed.
       */
      notes?: string[];
      /**
       * When a sentence has both features and look (D-191), ops handle only features, and the
       * remaining look requests are written here (a sentence in the interface language). After
       * completion, it turns into a "Keep tweaking" preset that enters the draft on tap.
       */
      next?: string;
      /**
       * AI-suggested next steps (D-355): one or two common subsequent additions for this app
       * (either features or look), as short phrases in the interface language. They appear as
       * clickable sentences on the AI modification page, which fill the input box upon tapping.
       * They do not perform tasks for the user, only suggest app modifications.
       */
      suggest?: string[];
    }
  | BuildPlan
  | { kind: 'restorePrevious' }
  | { kind: 'reject'; reason: RejectReason; message: string; examples: string[] };

/** Type of an item in the tool list and build plan (AGENT_PLAN §1, §3.5). */
export type WorkKind = 'file' | 'record' | 'fileToRecord' | 'look';
export const WORK_KINDS = [
  'file',
  'record',
  'fileToRecord',
  'look',
] as const satisfies readonly WorkKind[];

/** A step in the build plan: request is a request that can be sent to the AI individually, with no operations (AGENT_PLAN §3.9). */
export interface BuildStep {
  id: string;
  kind: WorkKind;
  title: string;
  request: string;
}

/**
 * Build plan for a large project (rule 53): no operations, presented to the user first. The user
 * taps "Start" to execute it step by step (invariant 16, D-415). Step count and fields are
 * validated by PlanSchema; the plan itself is just text and runs no tools (invariant 6).
 */
export interface BuildPlan {
  kind: 'build';
  summary: string;
  steps: BuildStep[];
}

/** Maximum number of steps in a plan. */
export const BUILD_MIN_STEPS = 2;
export const BUILD_MAX_STEPS = 8;

/** Maximum length of a note in characters. Truncated when too long (D14): a valid modification should not be invalidated solely because a note is too long. */
const NOTE_MAX = 200;
/** Do not leave half an emoji when truncating. */
const cutNote = (note: string) => note.slice(0, NOTE_MAX).replace(/[\uD800-\uDBFF]$/, '');

export const PlanSchema: z.ZodType<Plan> = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('ops'),
    ops: OpListSchema,
    homeEntry: z.boolean().optional(),
    notes: z.array(z.string().min(1).transform(cutNote)).max(4).optional(),
    next: z.string().min(1).max(200).optional(),
    suggest: z.array(z.string().min(1).max(80)).max(2).optional(),
  }),
  z.strictObject({
    kind: z.literal('build'),
    summary: z
      .string()
      .trim()
      .min(1)
      .transform((x) => cutNote(x)),
    steps: z
      .array(
        z.strictObject({
          id: z.string().min(1).max(64),
          kind: z.enum(WORK_KINDS),
          title: z
            .string()
            .trim()
            .min(1)
            .transform((x) => x.slice(0, 80).replace(/[\uD800-\uDBFF]$/, '')),
          // Do not truncate: cutting a sentence in half creates a different request, so send excessively long requests back to be rewritten.
          request: z.string().trim().min(1).max(500),
        }),
      )
      .min(BUILD_MIN_STEPS)
      .max(BUILD_MAX_STEPS)
      .refine((steps) => new Set(steps.map((s) => s.id)).size === steps.length, {
        message: 'step ids must be different',
      }),
  }),
  z.strictObject({ kind: z.literal('restorePrevious') }),
  z.strictObject({
    kind: z.literal('reject'),
    reason: z.enum(REJECT_REASONS),
    message: z.string(),
    examples: z.array(z.string()),
  }),
]) as z.ZodType<Plan>;

/**
 * Where the user opened AI modification from (D-124). Structure only, no content:
 * - workflow: opened from a quick action ("Let AI modify this"), where "this" and "it" refer to
 * that action.
 * - chain: opened from the result of two successful sequential operations, containing two
 * sequential quick action IDs without file info.
 * - shared: opened from the inbox page, carrying the type and count of shared files (no file
 * names, sizes, or content).
 * - page: opened from an entry point in the top-right corner of a page (D-406), with only the
 * page ID; "this page" and "here" refer to it.
 * - table: opened from a record form or "Done" page of a table (D-406), with only the table ID
 * and no records.
 * - screen: opened from built-in tool or quick action pages in Morph (D-406): the pages
 * themselves cannot be modified, but tools and quick actions can be added.
 * - desk: opened from the file desk (D-406), with only the types of files on the desk; allows
 * modifying toolbars and layout, but cannot touch files (invariant 3).
 */
export type PlanAbout =
  | { kind: 'workflow'; workflowId: string }
  | { kind: 'chain'; first: string; second: string }
  | {
      kind: 'shared';
      images: number;
      pdfs: number;
      others: number;
      /** Videos and audio (D-147); older apps do not send them, so optional. */
      videos?: number | undefined;
      audio?: number | undefined;
    }
  | { kind: 'page'; pageId: string }
  | { kind: 'table'; tableId: string }
  | { kind: 'screen'; screen: 'tools' | 'quickActions' }
  | { kind: 'desk'; fileKind: DeskKind };

export const PlanAboutSchema: z.ZodType<PlanAbout> = z.discriminatedUnion('kind', [
  z.strictObject({
    kind: z.literal('chain'),
    first: z.string().min(1).max(64),
    second: z.string().min(1).max(64),
  }),
  z.strictObject({ kind: z.literal('workflow'), workflowId: z.string().min(1).max(64) }),
  z.strictObject({
    kind: z.literal('shared'),
    images: z.number().int().min(0).max(100),
    pdfs: z.number().int().min(0).max(100),
    others: z.number().int().min(0).max(100),
    videos: z.number().int().min(0).max(100).optional(),
    audio: z.number().int().min(0).max(100).optional(),
  }),
  z.strictObject({ kind: z.literal('page'), pageId: z.string().min(1).max(64) }),
  z.strictObject({ kind: z.literal('table'), tableId: z.string().min(1).max(64) }),
  z.strictObject({ kind: z.literal('screen'), screen: z.enum(['tools', 'quickActions']) }),
  z.strictObject({
    kind: z.literal('desk'),
    fileKind: z.enum(['image', 'pdf', 'sheet', 'doc', 'video', 'audio', 'other']),
  }),
]);

/**
 * A statement made earlier in the same draft (D-207), with the oldest first. done: completed, the
 * modification is already in the config; reply: what was changed when completed (the lines shown
 * to the user), or the reason if not completed.
 */
export interface PlanEarlier {
  input: string;
  done: boolean;
  reply: string;
}

/** An unfinished item in the tool list (AGENT_PLAN §3.5). */
export interface PlanSessionItem {
  kind: WorkKind;
  text: string;
  status: 'todo' | 'failed';
  reason?: string;
}

/**
 * The <session> block sent to the model (D-414): goal, unfinished items, and recent statements.
 * Contains only user statements, a plan sentence, and config structure, with no record content
 * (invariants 1, 2, and 14). step: the current step number of the build plan (counted from 1),
 * during which only operations can be returned; remaining is the number of subsequent steps.
 */
export interface PlanSession {
  goal?: string;
  open: PlanSessionItem[];
  recent: PlanEarlier[];
  step?: { index: number; total: number; remaining: number };
}

export interface PlanContext {
  config: WorkspaceConfig;
  registry: Registry;
  /** Interface language: reject explanations and examples in other languages. */
  locale: Locale;
  about?: PlanAbout;
  /**
   * Tink opened within a specific app (D-485): can only modify this app. Coexists with about
   * (about specifies which page it was opened from, scope specifies which app). The configuration
   * sent to the model contains only this app's portion, and changes are validated by code against
   * the scope (scope in change.ts). Not included when opened from the home screen.
   */
  scope?: { appId: string };
  /** Used only by evaluations and older callers; apps send session (D-414). */
  earlier?: PlanEarlier[];
  session?: PlanSession;
  /** Where the planning progress is at (D-448): the AI page displays a short message next to Tink. Reports stage only, without sentences or configuration. */
  onProgress?: (step: PlanProgress) => void;
}

/**
 * Planning stages (D-448): the first five correspond to the prompt sections shown to the model
 * this time (all / files / records / pages / style), checking indicates validating the
 * modifications provided by the model, and fixing indicates explaining issues to the model and
 * re-querying.
 */
export type PlanProgress = 'full' | 'files' | 'records' | 'look' | 'style' | 'checking' | 'fixing';

export interface AIProvider {
  plan(input: string, ctx: PlanContext): Promise<Plan>;
}
