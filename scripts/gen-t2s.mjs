// Generates packages/core/src/ocr-t2s.ts (D-268): a single-character Traditional-to-Simplified
// Chinese mapping table from OpenCC (Apache-2.0) TSCharacters.txt and STCharacters.txt. Only
// includes 1-to-1 mappings where the Traditional character is not also used as a Simplified
// character (e.g. U+4E7E, U+65BC, U+5925 are also used in Simplified — skipped if mapped to
// themselves or if they appear as Simplified targets in STCharacters) so conversion never corrupts
// valid text. Usage: node scripts/gen-t2s.mjs <TSCharacters.txt> <STCharacters.txt>
import fs from 'node:fs';

const [tsPath, stPath] = process.argv.slice(2);
if (!tsPath || !stPath)
  throw new Error('usage: node scripts/gen-t2s.mjs TSCharacters.txt STCharacters.txt');
const rows = (file) =>
  fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .filter((l) => l && !l.startsWith('#'))
    .map((l) => {
      const [key, values] = l.split('\t');
      return [key, values.split(' ')];
    });
const simplified = new Set(rows(stPath).map(([key]) => key));
let from = '';
let to = '';
for (const [t, options] of rows(tsPath)) {
  if ([...t].length !== 1 || options.includes(t) || simplified.has(t)) continue;
  const s = options[0];
  if ([...s].length !== 1) continue;
  from += t;
  to += s;
}
const out = `// Generated by scripts/gen-t2s.mjs — do not edit by hand (D-268). Data from OpenCC (https://github.com/BYVoid/OpenCC, Apache-2.0).
// Traditional -> Simplified Chinese: the two strings correspond 1-to-1 by code point (some characters are outside the BMP).

export const T2S_FROM = ${JSON.stringify(from)};
export const T2S_TO = ${JSON.stringify(to)};
`;
fs.writeFileSync(new URL('../packages/core/src/ocr-t2s.ts', import.meta.url), out);
console.log(`${[...from].length} characters`);
