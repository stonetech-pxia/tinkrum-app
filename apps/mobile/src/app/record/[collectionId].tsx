import {
  appViewOf,
  attachmentIds,
  formInput,
  issuesLeft,
  tableIsShown,
  type DataRecord,
  type FieldIssue,
} from '@morph/core';
import { Stack, useLocalSearchParams } from 'expo-router';
import { useHeaderHeight } from 'expo-router/react-navigation';
import { useEffect, useRef, useState } from 'react';
import { Alert, KeyboardAvoidingView, ScrollView, Text, View } from 'react-native';

import { deliverLinkPick } from '@/data/link-pick';
import { useComputedRecords, useRecordActions, type SaveResult } from '@/data/records';
import { useSimilarCheck } from '@/data/similar-records';
import { t } from '@/i18n';
import { FormFilesContext } from '@/renderer/Attachments';
import { newFormValues, prefillFormValues, toFormValues } from '@/renderer/data';
import { RecordActionRow } from '@/renderer/RecordActionRow';
import { SuggestedFields } from '@/renderer/SuggestedFields';
import { usePalette } from '@/renderer/theme';
import { Button } from '@/renderer/ui';
import { takeFormCopies } from '@/share/save-as-record';
import { tableEntry } from '@/shell/ai-entry';
import { stackScreenOptions } from '@/shell/header';
import { useConfirmLeave } from '@/shell/useConfirmLeave';
import type { StoredRecord } from '@/storage/types';
import { deleteUserFiles } from '@/storage/user-files';
import { useCalendar, useWorkspace, useWorkspaceContext } from '@/workspace/context';

/**
 * Record edit page: generated by core according to table fields. Form layout configuration since
 * D-570: form layout on table (sections, conditional visibility per field), hint and min/max on
 * fields; saving, deletion, attachments, candidate values, and other page sections remain handled
 * by core.
 */
export default function RecordRoute() {
  const { collectionId, recordId, prefill, copies, pickFor } = useLocalSearchParams<{
    collectionId: string;
    recordId?: string;
    /** New record form opened via one-tap action (D-338): preset values in JSON. */
    prefill?: string;
    /** Inbox "Save as record" (D-392): keys of user files copied for this form (share/save-as-record.ts). */
    copies?: string;
    /** Opened via "Add new" from relation field (D-546): returns record ID to that input field upon saving. */
    pickFor?: string;
  }>();
  const { repo, files, locale, registry } = useWorkspaceContext();
  const bumpAssets = useWorkspace((s) => s.bumpAssets);
  const showToast = useWorkspace((s) => s.showToast);
  const config = useWorkspace((s) => s.config)!;
  // Record page uses the style of its parent app (D-485); home screen tables use the home screen style.
  const palette = usePalette(
    appViewOf(config, config.data.tables.find((c) => c.id === collectionId)?.app ?? null).theme,
  );
  const actions = useRecordActions();
  const cal = useCalendar();
  const mayProceed = useSimilarCheck();
  const headerHeight = useHeaderHeight();
  const collection = config.data.tables.find((c) => c.id === collectionId);
  // Lookup, aggregation, previous record (D-291): displays computed values after saving this record.
  const computed = useComputedRecords(config.data.tables, collection, cal);
  const [record, setRecord] = useState<DataRecord | null | undefined>(recordId ? undefined : null);
  const [values, setValues] = useState<Record<string, unknown>>(() =>
    !recordId && collection
      ? {
          ...newFormValues(collection, cal),
          ...(prefill ? prefillFormValues(collection, prefill) : {}),
        }
      : {},
  );
  // Values upon opening: prompts "Discard changes?" if leaving with filled or modified unsaved data (2026-11-06 test: inputted text was directly lost).
  const [initial, setInitial] = useState(() => JSON.stringify(values));
  const leave = useConfirmLeave(JSON.stringify(values) !== initial, 'formDiscardMessage', locale);
  const [issues, setIssues] = useState<FieldIssue[]>([]);
  // Clears field error upon modification (D-572, simulator check P3: red text persisting after correction required waiting for next save).
  const edit = (next: Record<string, unknown>) => {
    setIssues((now) => issuesLeft(now, values, next));
    setValues(next);
  };
  // Files copied from inbox (D-392) and attachments returned from desk (D-395): delete upon leaving
  // this page if not saved into this record (deleted entirely if leaving without saving). These are
  // newly created by this form; originals, inbox batch, and files originally in the record are
  // untouched.
  const [copied] = useState(() => (recordId ? [] : takeFormCopies(copies)));
  const owned = useRef<Set<string>>(new Set(copied));
  const [formFiles] = useState(() => ({
    hold: (ids: readonly string[]) => ids.forEach((id) => owned.current.add(id)),
  }));
  const kept = useRef<Set<string>>(new Set());
  useEffect(
    () => () => {
      const unused = [...owned.current].filter((id) => !kept.current.has(id));
      if (unused.length === 0) return;
      void deleteUserFiles(unused, repo, files)
        .then(bumpAssets)
        .catch(() => undefined);
    },
    [repo, files, bumpAssets],
  );

  useEffect(() => {
    if (!recordId || !collection) return;
    void repo.getRecord(recordId).then((r) => {
      const active = r && r.deletedAt === null ? r : null;
      setRecord(active);
      const loaded = toFormValues(collection, active);
      setValues(loaded);
      setInitial(JSON.stringify(loaded));
    });
  }, [repo, recordId, collection]);

  if (!collection) {
    return (
      <View style={{ flex: 1, padding: 24, justifyContent: 'center' }}>
        <Text style={[palette.font('body', 15), { color: palette.muted }]}>
          {t(locale, 'tableMissing')}
        </Text>
      </View>
    );
  }

  async function save() {
    if (!collection) return;
    // D-570: fields in hidden sections are not submitted (stored values untouched), invisible errors do not block saving.
    const input = formInput(collection, values, new Date(), cal);
    // D-426: prompt only for new records, user can always choose "Save anyway".
    if (!record && !(await mayProceed(collection, input))) return;
    const result = record
      ? await actions.update(collection, record, input)
      : await actions.add(collection, input);
    finish(result);
  }

  /** Save result: return upon successful save; highlight invalid inputs; prompt if record was modified or deleted elsewhere while editing. */
  function finish(result: SaveResult) {
    if (!collection) return;
    if (result.ok) {
      kept.current = new Set(
        collection.fields.flatMap((f) => (f.type === 'file' ? attachmentIds(values[f.id]) : [])),
      );
      if (!record && pickFor && 'id' in result) deliverLinkPick(pickFor, result.id);
      leave();
      // New record not visible when going back (this table has not been read by any page yet): tell the user, they can continue editing.
      if (!record && !tableIsShown(config, collection.id, registry))
        showToast({
          message: t(locale, 'recordSavedNoPage'),
          continueTable: collection.id,
        });
    } else if ('issues' in result) setIssues(result.issues);
    else if ('conflict' in result) askConflict(result.conflict);
    else if ('gone' in result)
      Alert.alert(t(locale, 'recordConflictGoneTitle'), t(locale, 'recordConflictGoneMessage'), [
        { text: t(locale, 'ok'), onPress: () => leave() },
      ]);
  }

  /** After opening, this record was modified elsewhere (notification button, home screen widget, etc.): do not quietly revert to the old value, let the user choose (R05). */
  function askConflict(latest: StoredRecord) {
    Alert.alert(t(locale, 'recordConflictTitle'), t(locale, 'recordConflictMessage'), [
      { text: t(locale, 'recordConflictKeep'), onPress: () => void keepMine(latest) },
      { text: t(locale, 'recordConflictLatest'), onPress: () => adoptLatest(latest) },
      { text: t(locale, 'cancel'), style: 'cancel' },
    ]);
  }

  /** Only save items I modified in this form; keep current values for other items (just modified elsewhere). */
  async function keepMine(latest: StoredRecord) {
    if (!collection) return;
    const opened = JSON.parse(initial) as Record<string, unknown>;
    const mine = Object.fromEntries(
      Object.entries(formInput(collection, values, new Date(), cal)).filter(
        ([key, v]) => JSON.stringify(v) !== JSON.stringify(opened[key]),
      ),
    );
    finish(await actions.update(collection, latest, mine));
  }

  /** Discard my modifications: revert form to the currently saved version, continue viewing and editing. */
  function adoptLatest(latest: StoredRecord) {
    if (!collection) return;
    const loaded = toFormValues(collection, latest);
    setRecord(latest);
    setValues(loaded);
    setInitial(JSON.stringify(loaded));
    setIssues([]);
  }

  async function remove() {
    if (!record) return;
    await actions.remove(record);
    leave();
  }

  return (
    <KeyboardAvoidingView
      style={{ flex: 1, backgroundColor: palette.background }}
      // Android is edge-to-edge, window does not shrink when keyboard appears (on real devices, keyboard covers fields below): reserve keyboard height on both sides.
      behavior="padding"
      // This page is below the title bar: keyboard position is calculated from the full screen; without this height offset, fields below cannot be revealed.
      keyboardVerticalOffset={headerHeight}>
      <Stack.Screen
        options={{
          ...stackScreenOptions(palette),
          // Editing an existing record: title is just "Edit" (D-590); new record still includes table name.
          title: record ? t(locale, 'edit') : `${collection.name} · ${t(locale, 'newRecord')}`,
          headerRight: tableEntry(collection.id, palette),
        }}
      />
      {record === undefined ? null : (
        <ScrollView
          contentContainerStyle={{ padding: palette.pad, gap: palette.gap, paddingBottom: 48 }}
          keyboardShouldPersistTaps="handled">
          {record ? (
            <RecordActionRow
              collection={collection}
              record={computed.records?.find((r) => r.id === record.id) ?? record}
              values={values}
              palette={palette}
            />
          ) : null}
          <FormFilesContext.Provider value={formFiles}>
            <SuggestedFields
              suggest={!recordId}
              collection={collection}
              values={values}
              onChange={edit}
              issues={issues}
              palette={palette}
              locale={locale}
              testPrefix="editor"
              related={
                computed.view && {
                  view: computed.view,
                  record: computed.records?.find((r) => r.id === recordId) ?? null,
                }
              }
            />
          </FormFilesContext.Provider>
          {/* When save is rejected (D-572, simulator check P2): save button is at the very bottom of long forms, but the error field is above; state how many items failed and where they are marked. */}
          {issues.length > 0 ? (
            <Text
              testID="editor-issues"
              accessibilityLiveRegion="polite"
              style={[palette.font('bodyMedium', 14), { color: palette.danger }]}>
              {t(locale, 'formIssues', { n: new Set(issues.map((i) => i.fieldId)).size })}
            </Text>
          ) : null}
          <Button
            palette={palette}
            testID="editor-save"
            label={t(locale, 'save')}
            onPress={() => void save()}
          />
          {record ? (
            <Button
              palette={palette}
              testID="editor-delete"
              variant="outline"
              danger
              label={t(locale, 'delete')}
              onPress={() => void remove()}
            />
          ) : null}
        </ScrollView>
      )}
    </KeyboardAvoidingView>
  );
}
