import {
  deskToolIcon,
  deskToolWorkflow,
  deskWorkflowFits,
  findWorkflow,
  localize,
  type DeskFile,
  type DeskIcon,
  type DeskGroup,
  type DeskGroupId,
  type DeskKind,
  type DeskTool,
  type IconValue,
  type Locale,
  type Registry,
  type Workflow,
} from '@morph/core';
import { useRef, useState } from 'react';
import {
  Pressable,
  ScrollView,
  type ScrollViewInstance,
  StyleSheet,
  Text,
  View,
} from 'react-native';

import { t, type StringKey } from '../i18n';
import { Icon } from '../renderer/Icon';
import type { Palette } from '../renderer/theme';
import { runsHere, UNSUPPORTED_ACTIONS } from '../runtime/device-support';

// Room toolbar (file-room DESIGN §4, §5, D-359): a row of horizontally scrolling icons plus text,
// arranged by group. Groups and tools come from layout configuration (if omitted, generated by the
// registry based on file type, see deskToolbar in @morph/core). Items that cannot process these
// files on the desk become grayed out and unclickable. Buttons only execute when the user taps them
// (D-113). Fixed group "File" at the end (share, save, system preview, D-363): room's own business,
// not in configuration, present for every file type, toolbar will never be empty.

const GROUP_TITLE: Record<DeskGroupId, StringKey> = {
  edit: 'deskGroupEdit',
  annotate: 'deskGroupAnnotate',
  pages: 'deskGroupPages',
  adjust: 'deskGroupAdjust',
  convert: 'deskGroupConvert',
  quick: 'deskGroupQuick',
};

/** "File" group: room's own buttons. */
export type RoomTool = 'share' | 'save' | 'folder' | 'preview';

export interface ToolEntry {
  key: string;
  /** Tool, quick action; buttons in the "File" group do not have this. */
  item?: DeskTool;
  room?: RoomTool;
  label: string;
  icon: IconValue | DeskIcon;
  /** Quick action (workflow); absent for tools. */
  workflow?: Workflow;
  enabled: boolean;
}

/** Name, icon, and availability of each item on the toolbar. */
export function toolEntries(
  groups: readonly DeskGroup[],
  targets: readonly DeskFile[],
  registry: Registry,
  workflows: readonly Workflow[],
  locale: Locale,
): { title: string; entries: ToolEntry[] }[] {
  return groups.map((g) => ({
    title: g.title ?? (g.id ? t(locale, GROUP_TITLE[g.id]) : ''),
    entries: g.items.flatMap((item, i): ToolEntry[] => {
      if (typeof item === 'object') {
        const action = registry.actions.get(item.action);
        if (!action || UNSUPPORTED_ACTIONS.has(action.id)) return [];
        const preset = item.preset ? action.presets?.find((p) => p.id === item.preset) : undefined;
        return [
          {
            key: `${item.action}-${item.preset ?? ''}-${i}`,
            item,
            label: localize(preset?.label ?? action.label, locale) ?? action.id,
            icon: deskToolIcon(action, registry, item.preset),
            enabled:
              deskToolWorkflow(
                action.id,
                targets,
                registry,
                preset ? { ...preset.values } : undefined,
              ) !== null,
          },
        ];
      }
      const workflow = findWorkflow(workflows, item, locale);
      if (!workflow || !runsHere(workflow)) return [];
      return [
        {
          key: `wf-${workflow.id}-${i}`,
          item,
          label: workflow.name,
          icon: workflow.icon ?? 'workflow',
          workflow,
          enabled: deskWorkflowFits(workflow, targets),
        },
      ];
    }),
  }));
}

/** "File" group (present for all file types). */
export function roomEntries(
  locale: Locale,
  /** PDF desk keeps only share (saving is handled by "Finish", system preview is not needed). */
  kind?: DeskKind,
): { title: string; entries: ToolEntry[] } {
  const entry = (room: RoomTool, label: StringKey, icon: DeskIcon): ToolEntry => ({
    key: `room-${room}`,
    room,
    label: t(locale, label),
    icon,
    enabled: true,
  });
  return {
    title: t(locale, 'deskGroupFile'),
    entries:
      kind === 'pdf'
        ? [entry('share', 'resultShare', 'share')]
        : [
            entry('share', 'resultShare', 'share'),
            entry('save', 'resultSave', 'save'),
            entry('folder', 'resultFolder', 'folder'),
            entry('preview', 'deskToolPreview', 'preview'),
          ],
  };
}

export function DeskToolbar({
  groups,
  palette,
  disabled,
  onPress,
}: {
  groups: { title: string; entries: ToolEntry[] }[];
  palette: Palette;
  /** The entire row is unclickable while running a tool. */
  disabled: boolean;
  onPress: (entry: ToolEntry) => void;
}) {
  const scroll = useRef<ScrollViewInstance>(null);
  // When there are multiple groups, tabs are shown at the top, and the bottom displays only the
  // current group (2026-11-06: when all groups are arranged in a long strip, later groups are short
  // and cannot be scrolled fully to the left, making "Process", "Convert", and "File" look like the
  // same row, and tapping back to "Markup" does not jump accordingly).
  const [active, setActive] = useState(0);
  const tabs = groups.length > 1;
  const at = Math.min(active, groups.length - 1);
  const shown = tabs ? [groups[at]!] : groups;
  return (
    <View>
      {tabs ? (
        <ScrollView
          horizontal
          showsHorizontalScrollIndicator={false}
          testID="desk-tabs"
          contentContainerStyle={styles.tabs}>
          {groups.map((g, gi) => (
            <Pressable
              key={`${gi}-${g.title}`}
              testID={`desk-tab-${gi}`}
              accessibilityRole="tab"
              accessibilityState={{ selected: gi === at }}
              onPress={() => {
                setActive(gi);
                scroll.current?.scrollTo({ x: 0, animated: false });
              }}
              style={[
                styles.tab,
                { backgroundColor: gi === at ? palette.primaryTint : 'transparent' },
              ]}>
              <Text
                style={[
                  palette.font(gi === at ? 'bodyBold' : 'bodyMedium', 14),
                  { color: gi === at ? palette.primaryText : palette.caption },
                ]}>
                {g.title}
              </Text>
            </Pressable>
          ))}
        </ScrollView>
      ) : null}
      <ScrollView
        ref={scroll}
        horizontal
        showsHorizontalScrollIndicator={false}
        testID="desk-toolbar"
        contentContainerStyle={styles.row}>
        {shown.map((g, gi) => (
          <View
            key={`${gi}-${g.title}`}
            style={[
              styles.group,
              gi > 0 && { borderLeftWidth: StyleSheet.hairlineWidth, borderColor: palette.border },
            ]}>
            {!tabs && g.title ? (
              <Text
                style={[palette.font('bodyBold', 11), styles.title, { color: palette.caption }]}>
                {g.title}
              </Text>
            ) : null}
            <View style={styles.items}>
              {g.entries.map((entry) => {
                const off = disabled || !entry.enabled;
                return (
                  <Pressable
                    key={entry.key}
                    testID={`desk-tool-${toolTestId(entry)}`}
                    accessibilityRole="button"
                    accessibilityState={{ disabled: off }}
                    disabled={off}
                    onPress={() => onPress(entry)}
                    style={({ pressed }) => [
                      styles.item,
                      { opacity: off ? 0.35 : pressed ? 0.6 : 1 },
                    ]}>
                    <View style={[styles.itemIcon, { backgroundColor: palette.primaryTint }]}>
                      <Icon name={entry.icon} size={21} color={palette.primaryText} />
                    </View>
                    <Text
                      numberOfLines={2}
                      style={[
                        palette.font('bodyMedium', 11),
                        styles.label,
                        { color: palette.text },
                      ]}>
                      {entry.label}
                    </Text>
                  </Pressable>
                );
              })}
            </View>
          </View>
        ))}
      </ScrollView>
    </View>
  );
}

const toolTestId = (entry: ToolEntry) =>
  entry.room
    ? `room-${entry.room}`
    : typeof entry.item === 'object'
      ? entry.item.action
      : (entry.item ?? entry.key);

const styles = StyleSheet.create({
  row: { paddingHorizontal: 8, paddingTop: 4, paddingBottom: 8, alignItems: 'flex-start' },
  group: { paddingHorizontal: 6, gap: 2 },
  // D-488: Tabs are light pills (selected background is the theme's light primary color), icons are placed inside circular backgrounds.
  tabs: { paddingHorizontal: 12, paddingTop: 10, paddingBottom: 2, gap: 6 },
  tab: { paddingHorizontal: 14, paddingVertical: 6, borderRadius: 999 },
  title: { paddingHorizontal: 4, letterSpacing: 0.4 },
  items: { flexDirection: 'row' },
  item: { width: 68, alignItems: 'center', gap: 4, paddingVertical: 6 },
  itemIcon: {
    width: 40,
    height: 40,
    borderRadius: 20,
    alignItems: 'center',
    justifyContent: 'center',
  },
  label: { textAlign: 'center' },
});
