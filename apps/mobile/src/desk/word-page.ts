/**
 * Original image popup above the cursor (D-468): positions of each block (each cell for tables)
 * in the original image, and original images per page.
 */
export function jpegDataUrl(bytes: Uint8Array): string {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  let out = '';
  for (let i = 0; i < bytes.length; i += 3) {
    const a = bytes[i]!;
    const b = bytes[i + 1];
    const c = bytes[i + 2];
    out += chars[a >> 2]! + chars[((a & 3) << 4) | ((b ?? 0) >> 4)]!;
    out += b === undefined ? '=' : chars[((b & 15) << 2) | ((c ?? 0) >> 6)]!;
    out += c === undefined ? '=' : chars[c & 63]!;
  }
  const ext = imageExt(bytes);
  const type = ext === 'png' || ext === 'gif' || ext === 'bmp' ? ext : 'jpeg';
  return `data:image/${type};base64,${out}`;
}
